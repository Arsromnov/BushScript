static JSContext *JS_NewCustomContext(JSRuntime *rt)
{
  JSContext *ctx = JS_NewContext(rt);
  if (!ctx)
    return NULL;
  {
    extern JSModuleDef *js_init_module_std(JSContext *ctx, const char *name);
    js_init_module_std(ctx, "qjs:std");
  }
  return ctx;
}

